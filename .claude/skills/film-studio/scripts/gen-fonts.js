#!/usr/bin/env node
// Usage: node gen-fonts.js
// Reads every styles/*/design-system.json and writes components/engine/fonts.generated.ts:
// a map from font family to a lazy import of its @remotion/google-fonts module.
// Only fonts named in a design system can ever be loaded by a film.
const fs = require('fs');
const path = require('path');
const {COMPONENTS, FONT_ROLES, listStyles, loadDS, fontModule, fontInfo, fail} = require('./lib');

const fams = new Map();
for (const style of listStyles()) for (const p of loadDS(style).fonts) for (const r of FONT_ROLES) {
  const e = fams.get(p[r].family) ?? new Set();
  e.add(style);
  fams.set(p[r].family, e);
}
const missing = [...fams.keys()].filter((f) => !fontInfo(f));
if (missing.length) fail(`not in @remotion/google-fonts: ${missing.join(', ')}`);
const lines = [...fams.keys()].sort().map((f) => `\t${JSON.stringify(f)}: () => import('@remotion/google-fonts/${fontModule(f)}') as Promise<Mod>,`);
const out = `// GENERATED by scripts/gen-fonts.js from styles/*/design-system.json. Do not edit.
type Mod = {loadFont: (style?: any, options?: any) => {fontFamily: string; waitUntilDone: () => Promise<undefined>}};
export const FONT_LOADERS: Record<string, () => Promise<Mod>> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(COMPONENTS, 'engine', 'fonts.generated.ts'), out);
console.log(`PASS ${fams.size} font families mapped`);
